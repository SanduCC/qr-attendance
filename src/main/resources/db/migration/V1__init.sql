-- All timestamps are timestamptz (UTC); rendered in Europe/Bucharest by the app.

create table teacher (
    id          bigint generated by default as identity primary key,
    email       varchar(320) not null,
    name        varchar(200) not null,
    created_at  timestamptz  not null default now(),
    constraint uq_teacher_email unique (email)
);

create table course (
    id          bigint generated by default as identity primary key,
    teacher_id  bigint       not null references teacher (id) on delete cascade,
    name        varchar(200) not null,
    code        varchar(50)  not null,
    created_at  timestamptz  not null default now()
);
create index ix_course_teacher on course (teacher_id);

create table attendance_session (
    id                  uuid        primary key,
    course_id           bigint      not null references course (id) on delete cascade,
    opened_at           timestamptz not null,
    closes_at           timestamptz not null,
    status              varchar(10) not null,
    expected_headcount  integer,
    geofence_lat        double precision,
    geofence_lng        double precision,
    geofence_radius_m   integer,
    constraint ck_session_status check (status in ('OPEN', 'CLOSED')),
    constraint ck_session_window check (closes_at >= opened_at),
    constraint ck_session_headcount check (expected_headcount is null or expected_headcount > 0),
    constraint ck_session_geofence check (geofence_radius_m is null or geofence_radius_m > 0)
);
create index ix_session_course_opened on attendance_session (course_id, opened_at desc);
create index ix_session_open on attendance_session (closes_at) where status = 'OPEN';
create index ix_session_opened on attendance_session (opened_at);

create table student (
    id                bigint generated by default as identity primary key,
    provider          varchar(10)  not null,
    provider_subject  varchar(255) not null,
    email             varchar(320),
    first_name        varchar(100) not null,
    last_name         varchar(100) not null,
    created_at        timestamptz  not null default now(),
    constraint ck_student_provider check (provider in ('GOOGLE', 'APPLE')),
    -- Students are identified by the OAuth "sub" claim, never by email or name.
    constraint uq_student_provider_subject unique (provider, provider_subject)
);

create table attendance_record (
    id              bigint generated by default as identity primary key,
    session_id      uuid         not null references attendance_session (id) on delete cascade,
    student_id      bigint       not null references student (id) on delete cascade,
    checked_in_at   timestamptz  not null,
    device_id_hash  varchar(64)  not null,
    ip_hash         varchar(64)  not null,
    user_agent      varchar(512),
    -- Anti-cheat rule 3: one check-in per account per session.
    constraint uq_record_session_student unique (session_id, student_id),
    -- Anti-cheat rule 4: one check-in per device per session.
    constraint uq_record_session_device unique (session_id, device_id_hash)
);
create index ix_record_student on attendance_record (student_id);
